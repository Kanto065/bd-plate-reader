// Regenerates src/ml/classes.ts from the training files so the app and the
// training pipeline use the same class list.
//   node scripts/gen-classes.js          writes src/ml/classes.ts
//   node scripts/gen-classes.js check    exits with 1 if the file is stale
const fs = require('fs');
const path = require('path');

const TRAINING = path.join(__dirname, '..', '..', 'training');
const OUT = path.join(__dirname, '..', 'src', 'ml', 'classes.ts');

function build() {
  const strip = s => s.replace(/^﻿/, '');
  const names = strip(
    fs.readFileSync(path.join(TRAINING, 'classes.txt'), 'utf8'),
  )
    .split(/\r?\n/)
    .filter(line => line.trim().length > 0);
  const display = JSON.parse(
    strip(
      fs.readFileSync(path.join(TRAINING, 'class_display_bn.json'), 'utf8'),
    ),
  );
  const missing = names.filter(n => !(n in display));
  if (missing.length > 0) {
    throw new Error('No display text for: ' + missing.join(', '));
  }
  const lines = [];
  lines.push('// Generated by scripts/gen-classes.js from training/classes.txt and');
  lines.push('// training/class_display_bn.json. Do not edit by hand.');
  lines.push('');
  lines.push('export const CLASS_NAMES: readonly string[] = [');
  for (const n of names) {
    lines.push('  ' + JSON.stringify(n) + ',');
  }
  lines.push('];');
  lines.push('');
  lines.push('export const CLASS_DISPLAY: Readonly<Record<string, string>> = {');
  for (const n of names) {
    lines.push('  ' + JSON.stringify(n) + ': ' + JSON.stringify(display[n]) + ',');
  }
  lines.push('};');
  lines.push('');
  return lines.join('\n');
}

const content = build();
if (process.argv.includes("check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current.replace(/\r\n/g, '\n') !== content) {
    console.error('src/ml/classes.ts is stale. Run: node scripts/gen-classes.js');
    process.exit(1);
  }
  console.log('src/ml/classes.ts is up to date');
} else {
  fs.writeFileSync(OUT, content, 'utf8');
  console.log('Wrote ' + OUT);
}
