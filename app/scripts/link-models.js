// Copies the exported TFLite models into the app and generates
// src/ml/modelAssets.ts, which tells the app whether the models exist.
//
//   node scripts/link-models.js [folder]
//
// folder defaults to ../models (the repo level models folder). The files must
// be named plate_detector_int8.tflite and char_detector_int8.tflite. Metro
// resolves require() calls at bundle time, so a missing file would break the
// bundle. This script writes a require() only for files that exist.
const fs = require('fs');
const path = require('path');

const FILES = {
  PLATE_MODEL: 'plate_detector_int8.tflite',
  CHAR_MODEL: 'char_detector_int8.tflite',
};
const SOURCE = path.resolve(process.argv[2] || path.join(__dirname, '..', '..', 'models'));
const ASSETS = path.join(__dirname, '..', 'assets', 'models');
const OUT = path.join(__dirname, '..', 'src', 'ml', 'modelAssets.ts');

fs.mkdirSync(ASSETS, { recursive: true });
const lines = [
  '// Generated by scripts/link-models.js. Do not edit by hand.',
  '// A value is null when the model file is not bundled, and the app then',
  '// falls back to the placeholder plate.',
  '',
];
for (const [name, file] of Object.entries(FILES)) {
  const from = path.join(SOURCE, file);
  const to = path.join(ASSETS, file);
  if (fs.existsSync(from)) {
    fs.copyFileSync(from, to);
    console.log('Linked ' + file + ' (' + (fs.statSync(to).size / 1048576).toFixed(1) + ' MB)');
  }
  if (fs.existsSync(to)) {
    lines.push(
      'export const ' + name + ": number | null = require('../../assets/models/" + file + "');",
    );
  } else {
    lines.push('export const ' + name + ': number | null = null;');
    console.log('Missing ' + file + ', the app will use the placeholder');
  }
}
lines.push('');
fs.writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log('Wrote ' + OUT);
